"""The index of the emu snapshot fixtures (MC 17/11): python3 tools/hosttest/fixindex.py [CURRENT_BUILD_DIR] [--write]

For every set in internal/hosttest/fixtures/<name>/ (N.bin + N.json, tools/hosttest/snapshot.py): its label, build,
snapshot count, the tests that name it, whether it has a RECIPE.json (snapshot.py writes one since 17/11: the exact
command that regenerates it) and its state against CURRENT_BUILD_DIR (a HOSTTEST_SYMS build of today's tree; default
the fixture root's HTW/SWOS):
  CURRENT  today's code can be laid over its snapshots (emu.overlay: the layout matches);
  STALE    it cannot (LayoutChanged, or its own build dir is gone): the set still runs its OWN build's code in the tests
           that read it, but it does not test today's code. With a recipe it is regenerated by running RECIPE.json's
           `command`; without one (every set from before 17/11) only its owner can retake it.
Nothing is deleted or rewritten: --write puts INDEX.json and INDEX.md beside the fixtures (re-runs itself in the
host-test venv for Unicorn)."""
import glob
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
FIX = os.path.join(os.path.expanduser('~'), 'swos-mod', 'internal', 'hosttest', 'fixtures')
VENV = os.path.join(os.path.expanduser('~'), 'swos-mod', 'internal', 'hosttest', '.venv', 'bin', 'python')


def index(cur):
    sys.path.insert(0, HERE)
    sys.path.insert(0, os.path.join(HERE, '..'))
    import emu
    src = {os.path.basename(f): open(f).read() for f in glob.glob(os.path.join(HERE, 'tests', '*.py'))}
    out = {}
    for js in sorted(glob.glob(os.path.join(FIX, '*', '0.json'))):
        d = os.path.dirname(js)
        name, meta = os.path.basename(d), json.load(open(js))
        try:
            emu.Machine(d, 0, code_from=cur)
            state, why = 'CURRENT', 'today\'s code lays over it'
        except emu.LayoutChanged as e:
            state, why = 'STALE', 'LayoutChanged: ' + str(e)[:90]
        except FileNotFoundError as e:
            state, why = 'STALE', 'its build is gone: ' + str(e.filename or e)[:90]
        except Exception as e:                      # (a set this emu cannot open at all)
            state, why = 'STALE', f'{type(e).__name__}: {str(e)[:90]}'
        out[name] = {'state': state, 'why': why, 'label': meta.get('label'), 'build': meta.get('build'),
                     'snapshots': len(glob.glob(os.path.join(d, '[0-9]*.bin'))),
                     'recipe': os.path.isfile(os.path.join(d, 'RECIPE.json')),
                     'tests': sorted(f for f, t in src.items() if f"'{name}'" in t or f'"{name}"' in t)}
    return out


def main(argv):
    if sys.executable != VENV and os.path.exists(VENV) and not os.environ.get('HOSTTEST_NOVENV'):
        os.execv(VENV, [VENV, os.path.abspath(__file__)] + argv)
    sys.path.insert(0, HERE)
    import fixroot
    args = [a for a in argv if not a.startswith('--')]
    cur = args[0] if args else fixroot.fx('HTW', 'SWOS')
    ix = index(cur)
    n = {s: sum(1 for v in ix.values() if v['state'] == s) for s in ('CURRENT', 'STALE')}
    lines = [f'# Emu snapshot fixtures: index against {cur}', '',
             f'{len(ix)} sets: {n["CURRENT"]} CURRENT, {n["STALE"]} STALE; {sum(v["recipe"] for v in ix.values())} with a recipe. '
             'STALE = today\'s code cannot be laid over the set (it still runs its own build\'s code in its tests). '
             'Made by tools/hosttest/fixindex.py --write; nothing here is ever deleted by it.', '',
             '| set | state | recipe | snapshots | label | tests | why |', '|---|---|---|---|---|---|---|']
    for k, v in ix.items():
        lines.append(f"| {k} | **{v['state']}** | {'yes' if v['recipe'] else 'NO'} | {v['snapshots']} | {v['label']} | "
                     f"{', '.join(v['tests']) or '-'} | {v['why']} |")
    print('\n'.join(lines))
    if '--write' in argv:
        json.dump({'against': cur, 'sets': ix}, open(os.path.join(FIX, 'INDEX.json'), 'w'), indent=1, sort_keys=True)
        open(os.path.join(FIX, 'INDEX.md'), 'w').write('\n'.join(lines) + '\n')
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
